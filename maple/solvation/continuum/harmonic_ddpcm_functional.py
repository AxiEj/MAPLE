"""Disabled finite-dielectric smooth-partition harmonic ddPCM scalar.

The implementation retains the fixed local-potential Schwarz topology of the
validated harmonic ddCOSMO candidate, but replaces uniform COSMO dielectric
scaling by the published finite-dielectric two-stage equation

``A_epsilon G = A_infinity F`` and ``L X = G`` with ``F=-B c``.

The double-layer stage uses ddX's centered smooth characteristic and exterior
multipole continuation, assembled without a laboratory angular grid.  The
physical on-shell scalar is ``0.5*c.T*C*X``.  The first-stage and Schwarz
operators are generally nonsymmetric, so all derivatives are generated by
autodifferentiating this scalar through both solves.  This is a research
candidate and exposes no public E/F/H/V/M capability.
"""

